# Initial value
score = 50
print("Initial score:", score)

# += (Addition Assignment)
score += 10
print("After += :", score)

# -= (Subtraction Assignment)
score -= 5
print("After -= :", score)

# *= (Multiplication Assignment)
score *= 2
print("After *= :", score)

# /= (Division Assignment)
score /= 5
print("After /= :", score)

# //= (Floor Division Assignment)
score //= 2
print("After //= :", score)

# %= (Modulus Assignment)
score %= 3
print("After %= :", score)

# **= (Exponentiation Assignment)
score **= 3
print("After **= :", score)
#output:
# Initial score: 50
# After += : 60
# After -= : 55
# After *= : 110
# After /= : 22.0
# After //= : 11.0
# After %= : 2.0
# After **= : 8.0